class bankaccount
{
    #balance
    constructor(actHolder,initialactBalance)
    {
        this.actHolder=actHolder
        this.#balance=initialactBalance
    }
    showBalance()
    {
        console.log(this.#balance)
    }
    deposit(amt)
    {
        this.#balance+=amt
    }
    withdraw(amt)
    {
        this.#balance-=amt
    }
}
